def get_interaction_label(msgs: int) -> str:
    if msgs < 30:
        return "راقد عالودن 😴"
    elif msgs < 100:
        return "مقعمز في القهوة يتفرج ☕"
    elif msgs < 250:
        return "بادي يسخن ويهدرز ✨"
    elif msgs < 600:
        return "ناشط ومولع القروب 🔥"
    elif msgs < 1200:
        return "ركيزة القروب وهيبته 👑"
    elif msgs < 2500:
        return "عميد الهدرزة الليبية 🦁"
    return "أسطورة ليبيا في التفاعل 💎🇱🇾"

