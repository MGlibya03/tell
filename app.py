            orig_c = st_info["orig_cmd"]
            del pending_custom_cmd[chat_id]
            scs = get_group_json(chat_id, "shortcuts", {"ا": "ايدي", "ص": "صورتي", "ج": "جمالي"})
            scs[new_shortcut] = orig_c
            set_group_json(chat_id, "shortcuts", scs)
